import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = resolve(root, 'registry/statuses.json');
const checkOnly = process.argv.includes('--check');
const entries = JSON.parse(await readFile(registryPath, 'utf8'));

validateRegistry(entries);

const banner = '// Generated by scripts/generate-registry.mjs. Do not edit directly.\n';
const core = `${banner}export const STATUS_DEFINITIONS = ${JSON.stringify(
    entries.map(({ code, name, message }) => ({ code, name, message })),
    null,
    4,
)} as const;\n`;
const metadata = `${banner}export const STATUS_METADATA = ${JSON.stringify(entries, null, 4)} as const;\n`;
const constants = entries
    .map(({ code, name }) => `export const ${name} = ${code} as const;`)
    .join('\n');
const properties = entries.map(({ name }) => `    ${name},`).join('\n');
const codes = `${banner}${constants}\n\nexport const Status = Object.freeze({\n${properties}\n});\n`;

await emit('src/generated/statuses.ts', core);
await emit('src/generated/metadata.ts', metadata);
await emit('src/codes.ts', codes);

function validateRegistry(value) {
    if (!Array.isArray(value) || value.length === 0) {
        throw new Error('Registry must be a non-empty array.');
    }

    const codes = new Set();
    const names = new Set();
    for (const entry of value) {
        if (!Number.isInteger(entry.code) || entry.code < 100 || entry.code > 599) {
            throw new Error(`Invalid status code: ${entry.code}`);
        }
        if (!/^[A-Z][A-Z0-9_]*$/.test(entry.name)) {
            throw new Error(`Invalid status name: ${entry.name}`);
        }
        if (codes.has(entry.code)) throw new Error(`Duplicate status code: ${entry.code}`);
        if (names.has(entry.name)) throw new Error(`Duplicate status name: ${entry.name}`);
        codes.add(entry.code);
        names.add(entry.name);
    }
}

async function emit(relativePath, content) {
    const path = resolve(root, relativePath);
    const formatted = await format(content, {
        parser: 'typescript',
        printWidth: 100,
        tabWidth: 4,
        singleQuote: true,
        trailingComma: 'all',
    });
    if (checkOnly) {
        const current = await readFile(path, 'utf8').catch(() => '');
        if (current !== formatted) {
            throw new Error(`${relativePath} is stale. Run pnpm generate.`);
        }
        return;
    }
    await writeFile(path, formatted);
}
